def is_product_question(message: str) -> bool:
    """A question about PAW itself (how it works / how to use it), not about the user's projects."""
    msg = message or ""
    if re.search(_PRODUCT_SUBJECT, msg, re.I) and re.search(_HELP_WORDS, msg):
        return True
    return bool(re.search(_FEATURES, msg, re.I) and re.search(_HELP_WORDS, msg))


def search(message: str, limit: int = 3) -> list[dict[str, Any]]:
    """Rank guide sections by keyword overlap with the message; overview as a fallback."""
    msg = (message or "").lower()
    scored = []
    for entry in GUIDE:
        score = sum(2 if k.lower() in entry["title"].lower() else 1 for k in entry["keywords"] if k.lower() in msg)
        if score:
            scored.append((score, entry))
    scored.sort(key=lambda s: -s[0])
    hits = [e for _, e in scored[:limit]]
    return hits or [GUIDE[0]]


def as_context(entries: list[dict[str, Any]]) -> str:
    return "\n\n".join(f"【{e['title']}】\n{e['text']}" for e in entries)
